# 𝔽₂¹²⁸ = 𝔽₂⁶⁴[y]/(y² + xy + 1), leanVM's extension field E

const Iters = 2000

var rng: RngState
let seed = uint32(getTime().toUnix() and (1'i64 shl 32 - 1)) # unixTime mod 2^32
rng.seed(seed)
echo "\n------------------------------------------------------\n"
echo "t_gf2_64x2 xoshiro512** seed: ", seed
echo "Carry-less multiplication in hardware: ", hasClmulHardware()

# Independent reference
# ------------------------------------------------------------

func refMul(a, b: GF2_64x2): GF2_64x2 =
  ## The product written out in 𝔽₂⁶⁴, with y² = x·y + 1:
  ##   (a0 + a1·y)(b0 + b1·y) = (a0b0 + a1b1) + (a0b1 + a1b0 + x·a1b1)·y
  ## using only the portable base field arithmetic
  var a0b0, a1b1, a0b1, a1b0, xa1b1: GF2_64
  a0b0.prod_portable(a.c0, b.c0)
  a1b1.prod_portable(a.c1, b.c1)
  a0b1.prod_portable(a.c0, b.c1)
  a1b0.prod_portable(a.c1, b.c0)
  xa1b1.mulByX(a1b1)
  result.c0 = a0b0 + a1b1
  result.c1 = a0b1 + a1b0 + xa1b1

let Corners = [
  GF2_64x2.fromRaw(0, 0),
  GF2_64x2.fromRaw(1, 0),
  GF2_64x2.fromRaw(0, 1),
  GF2_64x2.fromRaw(high(uint64), high(uint64)),
  GF2_64x2.fromRaw(1'u64 shl 63, 1'u64 shl 63),
  GF2_64x2.fromRaw(0, high(uint64)),
  GF2_64x2.fromRaw(0xF000_0000_0000_0000'u64, 0xF000_0000_0000_0000'u64)]

proc randomE(rng: var RngState, i: int): GF2_64x2 =
  ## Cycle through uniform, high Hamming weight and long runs of 0 and 1
  case i mod 3
  of 0: rng.random_unsafe(GF2_64x2)
  of 1: rng.random_highHammingWeight(GF2_64x2)
  else: rng.random_long01Seq(GF2_64x2)

proc main() =
  suite "Binary field 𝔽₂¹²⁸ = 𝔽₂⁶⁴[y]/(y² + xy + 1)" & " [" & $WordBitWidth & "-bit words]":
    test "Reference vectors (leanVM, generated by an independent Python implementation)":
      type V = array[5, array[2, uint64]] # a, b, a·b, a², a⁻¹
      const Vectors: array[4, V] = [
        [[0x8a1d921ca352a3c3'u64, 0xa10d04b240699a83'u64], [0x936d4747ab0e6d1c'u64, 0xe46ab5adb68f9c7d'u64],
         [0xfbbffa3000b331c0'u64, 0xbf494d14ce4eadf8'u64], [0x3eb21e43df9bbb1c'u64, 0x7836265481e5ee7d'u64],
         [0x4dbcb8833d2c881c'u64, 0x01d5fd8ef4de46b1'u64]],
        [[0x4ced30628e0cd071'u64, 0xc694494e11044370'u64], [0x079184601cbc456d'u64, 0xc2b90e2d4a7acb31'u64],
         [0x1df92a5bbf394f60'u64, 0x4f9871091371b5d2'u64], [0x87f8c19a80de6b2b'u64, 0xe1b7b5434dbf44ba'u64],
         [0xe5886c008822ac39'u64, 0x5014981d45105c3b'u64]],
        [[0x1f7678795f345ff4'u64, 0xd584a285e92195e8'u64], [0xa4fab233b7895f8e'u64, 0xe8c4546870efc3e0'u64],
         [0x39944740fab79b32'u64, 0x677a979829fc8fea'u64], [0x33bf067a3def0161'u64, 0x7dd98b6fdaf72b54'u64],
         [0x126bd1f8da56668e'u64, 0xf1e4a54eaa0dc2d0'u64]],
        [[0xf8a7e4e12a61d563'u64, 0x852495966643d5c8'u64], [0x5b2495d1eb090346'u64, 0x786d6f68d7273a2f'u64],
         [0x6617b862c301fca8'u64, 0x1edae1e051362791'u64], [0xd03dc472c71a8299'u64, 0xab7efb6717791597'u64],
         [0x36a2e97ec7233d69'u64, 0xb5f24753a7ede4d1'u64]]]

      template e(x: array[2, uint64]): GF2_64x2 = GF2_64x2.fromRaw(x[0], x[1])

      for v in Vectors:
        let (a, b, ab, sq, ai) = (e(v[0]), e(v[1]), e(v[2]), e(v[3]), e(v[4]))
        var r: GF2_64x2
        r.prod(a, b)
        check: bool(r == ab)
        r.prod_portable(a, b)
        check: bool(r == ab)
        check: bool(refMul(a, b) == ab)
        r.square(a)
        check: bool(r == sq)
        r.square_portable(a)
        check: bool(r == sq)
        r.inv(a)
        check: bool(r == ai)

    test "The modulus: y² = x·y + 1":
      let y = GF2_64x2.fromRaw(0, 1)
      var r: GF2_64x2
      r.prod(y, y)
      check: bool(r == GF2_64x2.fromRaw(1, 2))
      r.prod_portable(y, y)
      check: bool(r == GF2_64x2.fromRaw(1, 2))

    test "Products, squares and mixed products match the reference, on every backend":
      proc checkMul(a, b: GF2_64x2) =
        let want = refMul(a, b)
        var r: GF2_64x2
        r.prod(a, b)
        doAssert bool(r == want)
        r.prod_portable(a, b)
        doAssert bool(r == want)

        # Aliasing
        r = a
        r *= b
        doAssert bool(r == want)
        r = b
        r.prod(a, r)
        doAssert bool(r == want)

        # Unreduced, then reduced
        var d, dp: GF2_64x2Dbl
        d.prod2x(a, b)
        dp.prod2x_portable(a, b)
        r.redc2x(d)
        doAssert bool(r == want)
        r.redc2x(dp)
        doAssert bool(r == want)

        # Squares
        let wantSq = refMul(a, a)
        r.square(a)
        doAssert bool(r == wantSq)
        r.square_portable(a)
        doAssert bool(r == wantSq)
        d.square2x(a)
        r.redc2x(d)
        doAssert bool(r == wantSq)

        # Mixed product by a base field element: a full product by an element with no y part
        let k = b.c1
        var kE: GF2_64x2
        kE.fromBase(k)
        let wantMixed = refMul(a, kE)
        r.prod(a, k)
        doAssert bool(r == wantMixed)
        r.prod_portable(a, k)
        doAssert bool(r == wantMixed)
        d.prod2x(a, k)
        r.redc2x(d)
        doAssert bool(r == wantMixed)
        r = a
        r *= k
        doAssert bool(r == wantMixed)

      for a in Corners:
        for b in Corners:
          checkMul(a, b)
      for i in 0 ..< Iters:
        checkMul(rng.randomE(i), rng.randomE(i+1))

    test "Field axioms, with Constantine's generic out-of-place operators":
      for i in 0 ..< Iters:
        let a = rng.randomE(i)
        let b = rng.randomE(i+1)
        let c = rng.randomE(i+2)
        check:
          bool(a * b == b * a)
          bool((a * b) * c == a * (b * c))
          bool(a * (b + c) == a * b + a * c)
          bool(a + a == GF2_64x2.getZero())
          bool(a - b == a + b)
          bool(a * GF2_64x2.getOne() == a)

    test "Conjugate: the Frobenius a^(2⁶⁴), and the norm":
      let y = GF2_64x2.fromRaw(0, 1)
      var r: GF2_64x2
      r.conj(y)
      check: bool(r == GF2_64x2.fromRaw(2, 1)) # y + x
      for i in 0 ..< 200:
        let a = rng.randomE(i)
        var frob, twice: GF2_64x2
        frob.square_repeated(a, 64)
        r.conj(a)
        check: bool(r == frob)
        twice.frobenius_map(a, 2)
        check: bool(twice == a)
        # The norm lies in the base field
        var n: GF2_64
        n.norm(a)
        var aConj: GF2_64x2
        aConj.prod(a, r)
        check:
          bool aConj.isBase()
          bool(aConj.c0 == n)
        # 128 squarings are the identity
        var r128: GF2_64x2
        r128.square_repeated(a, 128)
        check: bool(r128 == a)

    test "Inversion, including base field elements and zero":
      var z = GF2_64x2.getZero()
      z.inv()
      check: bool z.isZero()
      for i in 0 ..< Iters:
        let a = rng.randomE(i)
        var ai: GF2_64x2
        ai.inv(a)
        if bool a.isZero():
          check: bool ai.isZero()
        else:
          check: bool (a * ai).isOne()
        # Base field elements: the case the norm path is most likely to get wrong
        var k: GF2_64x2
        k.fromBase(a.c0)
        var ki: GF2_64x2
        ki.inv(k)
        var kiBase: GF2_64
        kiBase.inv(a.c0)
        check:
          bool ki.isBase()
          bool(ki.c0 == kiBase)

    test "Unreduced accumulation of full and mixed products equals the reduced sum":
      for _ in 0 ..< 100:
        var acc, t: GF2_64x2Dbl
        var want: GF2_64x2
        acc.setZero()
        want.setZero()
        for j in 0 ..< 16:
          let a = rng.randomE(j)
          let b = rng.randomE(j+1)
          let k = rng.random_unsafe(GF2_64)
          t.prod2x(a, b)
          acc += t
          t.prod2x(a, k)
          acc += t
          var ak: GF2_64x2
          ak.prod(a, k)
          want += a * b
          want += ak
        var r: GF2_64x2
        r.redc2x(acc)
        check: bool(r == want)

    test "sumprod (dot products), full and by base field elements, on every backend":
      const N = 13
      var a, b: array[N, GF2_64x2]
      var want = GF2_64x2.getZero()
      for i in 0 ..< N:
        a[i] = rng.randomE(i)
        b[i] = rng.randomE(i+1)
        want += a[i] * b[i]
      var r: GF2_64x2
      r.sumprod(a, b)
      check: bool(r == want)
      r.sumprod(a.toOpenArray(0, -1), b.toOpenArray(0, -1))
      check: bool r.isZero()

      for len in [0, 1, 2, 3, 7, 64, 255]:
        var xs = newSeq[GF2_64x2](len)
        var ys = newSeq[GF2_64x2](len)
        var ks = newSeq[GF2_64](len)
        var wantFull = GF2_64x2.getZero()
        var wantMixed = GF2_64x2.getZero()
        for i in 0 ..< len:
          xs[i] = rng.randomE(i)
          ys[i] = rng.randomE(i+1)
          ks[i] = rng.random_unsafe(GF2_64)
          wantFull += refMul(xs[i], ys[i])
          var kE: GF2_64x2
          kE.fromBase(ks[i])
          wantMixed += refMul(xs[i], kE)
        r.sumprod(xs, ys)
        check: bool(r == wantFull)
        r.sumprod_portable(xs, ys)
        check: bool(r == wantFull)
        r.sumprod(xs, ks)
        check: bool(r == wantMixed)
        r.sumprod_portable(xs, ks)
        check: bool(r == wantMixed)

    test "Constantine's generic exponentiation":
      for i in 0 ..< 100:
        let a = rng.randomE(i)
        var want = GF2_64x2.getOne()
        for e in 0'u64 ..< 20:
          var p = a
          p.pow_vartime(e)
          check: bool(p == want)
          want *= a
        # Exponent bytes, directly through the generic API
        var p = a
        p.pow_vartime([byte 0x01, 0x00], window = 4) # a^256
        var q: GF2_64x2
        q.square_repeated(a, 8)
        check: bool(p == q)

    test "Constantine's generic batch inversion, including zeros":
      const N = 37
      var src, dst, dstVartime: array[N, GF2_64x2]
      for i in 0 ..< N:
        src[i] = if i mod 5 == 2: GF2_64x2.getZero() else: rng.randomE(i)
      dst.batchInv(src)
      dstVartime.batchInv_vartime(src)
      for i in 0 ..< N:
        var want: GF2_64x2
        want.inv(src[i])
        check:
          bool(dst[i] == want)
          bool(dstVartime[i] == want)

    test "Constantine's generic tower operations behave as characteristic 2 requires":
      for i in 0 ..< 100:
        let a = rng.randomE(i)
        let b = rng.randomE(i+1)
        var r: GF2_64x2
        r.neg(a)
        check: bool(r == a)
        r.double(a)
        check: bool r.isZero()
        r.diff(a, b)
        check: bool(r == a + b)
        r = a
        r.ccopy(b, CtTrue)
        check: bool(r == b)
        r = a
        r.csetZero(CtTrue)
        check: bool r.isZero()
        r = a
        r.csetOne(CtTrue)
        check: bool r.isOne()
        r = a
        r.cadd(b, CtTrue)
        check: bool(r == a + b)
      check:
        bool GF2_64x2.getOne().isMinusOne()
        not compiles(GF2_64x2.getOne().div2())

    test "Constantine's generic multilinear extension evaluation":
      for numVars in [1, 2, 3, 5]:
        let L = 1 shl numVars
        var evals = newSeq[GF2_64x2](L)
        for i in 0 ..< L:
          evals[i] = rng.randomE(i)
        let mle = MultilinearExtension[GF2_64x2].new(numVars, evals)
        var xs = newSeq[GF2_64x2](numVars)
        for i in 0 ..< numVars:
          xs[i] = rng.randomE(i)

        # On the hypercube, the extension interpolates the evaluations
        for e in 0 ..< L:
          var point = newSeq[GF2_64x2](numVars)
          for i in 0 ..< numVars:
            point[i] = if ((e shr (numVars-1-i)) and 1) == 1: GF2_64x2.getOne() else: GF2_64x2.getZero()
          var r: GF2_64x2
          r.evalMultilinearExtensionAt(mle, point)
          check: bool(r == evals[e])

        # Off the hypercube, optimized and reference agree, in both bit orders
        for endian in [bigEndian, littleEndian]:
          var r, rRef: GF2_64x2
          if endian == bigEndian:
            r.evalMultilinearExtensionAt(mle, xs, bigEndian)
            rRef.evalMultilinearExtensionAt_reference(mle, xs, bigEndian)
          else:
            r.evalMultilinearExtensionAt(mle, xs, littleEndian)
            rRef.evalMultilinearExtensionAt_reference(mle, xs, littleEndian)
          check: bool(r == rRef)

    test "Serialization: little-endian is leanVM's wire format, round trips":
      for i in 0 ..< 100:
        let a = rng.randomE(i)
        var le, be: array[16, byte]
        check:
          le.marshal(a, littleEndian)
          be.marshal(a, bigEndian)
        for j in 0 ..< 8:
          check:
            le[j] == byte((a.c0.raw shr (8*j)) and 0xFF)
            le[8+j] == byte((a.c1.raw shr (8*j)) and 0xFF)
        for j in 0 ..< 16:
          check: be[j] == le[15-j]
        var b, c: GF2_64x2
        check:
          b.unmarshal(le, littleEndian)
          c.unmarshal(be, bigEndian)
          bool(a == b)
          bool(a == c)
          bool(GF2_64x2.fromHex(a.c0.toHex(), a.c1.toHex()) == a)
      # The generic extension field printer
      check: GF2_64x2.fromRaw(1, 2).toHex() ==
        "QuadraticExt(\n  c0: 0x0000000000000001, \n  c1: 0x0000000000000002)"

main()
