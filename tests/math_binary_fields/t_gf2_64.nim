# Independent references
# ------------------------------------------------------------

func refClmul(a, b: uint64): tuple[hi, lo: uint64] =
  ## Schoolbook: b·xⁱ for each set bit i of a
  for i in 0 ..< 64:
    if ((a shr i) and 1) == 1:
      result.lo = result.lo xor (b shl i)
      if i > 0:
        result.hi = result.hi xor (b shr (64 - i))

func refReduce(hi, lo: uint64): uint64 =
  ## Bit-by-bit long division by x⁶⁴ + x⁴ + x³ + x + 1
  var (hi, lo) = (hi, lo)
  for k in countdown(63, 0):
    if ((hi shr k) and 1) == 1:
      # xor (x⁶⁴ + 0x1B)·xᵏ
      hi = hi xor (1'u64 shl k)
      lo = lo xor (0x1B'u64 shl k)
      if k >= 60:
        hi = hi xor (0x1B'u64 shr (64 - k))
  return lo

func refMul(a, b: uint64): uint64 =
  let (hi, lo) = refClmul(a, b)
  refReduce(hi, lo)

const Corners = [0'u64, 1, 2, 0x1B, high(uint64), 1'u64 shl 63,
                 0xF000_0000_0000_0000'u64, 0x8000_0000_0000_001B'u64, 0x5555_5555_5555_5555'u64]

proc randomK(rng: var RngState, i: int): GF2_64 =
  ## Cycle through uniform, high Hamming weight and long runs of 0 and 1
  case i mod 3
  of 0: rng.random_unsafe(GF2_64)
  of 1: rng.random_highHammingWeight(GF2_64)
  else: rng.random_long01Seq(GF2_64)

proc main() =
  suite "Binary field 𝔽₂⁶⁴" & " [" & $WordBitWidth & "-bit words]":
    test "Reference vectors (leanVM, generated by an independent Python implementation)":
      const Vectors = [
        (0x01090913877ed8ed'u64, 0x66ab35ac2768468f'u64, 0x50c4519dc383744a'u64),
        (0xa7715ae18f12a3b5'u64, 0x05743059f43fa4f5'u64, 0xeb64cd9cd9cda6df'u64),
        (0xbd3efb4705e79ddd'u64, 0x3aff618604de4ae0'u64, 0xc3d7a95fa9cb59bb'u64)]
      for (a, b, c) in Vectors:
        var r, rp: GF2_64
        r.prod(GF2_64.fromRaw(a), GF2_64.fromRaw(b))
        rp.prod_portable(GF2_64.fromRaw(a), GF2_64.fromRaw(b))
        check:
          r.raw == c
          rp.raw == c
          refMul(a, b) == c

    test "Carry-less multiplication: hardware and portable match the schoolbook reference":
      proc checkClmul(a, b: uint64) =
        var hi, lo, hiP, loP: uint64
        clmul(hi, lo, a, b)
        clmul_portable(hiP, loP, a, b)
        let (hiR, loR) = refClmul(a, b)
        doAssert hi == hiR and lo == loR, "clmul " & $a & " " & $b
        doAssert hiP == hiR and loP == loR, "clmul_portable " & $a & " " & $b

        clsquare(hi, lo, a)
        clsquare_portable(hiP, loP, a)
        let (hiS, loS) = refClmul(a, a)
        doAssert hi == hiS and lo == loS
        doAssert hiP == hiS and loP == loS

      for a in Corners:
        for b in Corners:
          checkClmul(a, b)
      for i in 0 ..< Iters:
        checkClmul(rng.randomK(i).raw, rng.randomK(i+1).raw)

    test "Products and squares match the reference":
      proc checkMul(a, b: GF2_64) =
        let want = refMul(a.raw, b.raw)
        var r: GF2_64
        r.prod(a, b)
        doAssert r.raw == want
        r.prod_portable(a, b)
        doAssert r.raw == want
        r = a
        r *= b
        doAssert r.raw == want
        doAssert (a * b).raw == want

        var d: GF2_64Dbl
        d.prod2x(a, b)
        r.redc2x(d)
        doAssert r.raw == want

        r.square(a)
        doAssert r.raw == refMul(a.raw, a.raw)
        r.square_portable(a)
        doAssert r.raw == refMul(a.raw, a.raw)

      for a in Corners:
        for b in Corners:
          checkMul(GF2_64.fromRaw(a), GF2_64.fromRaw(b))
      for i in 0 ..< Iters:
        checkMul(rng.randomK(i), rng.randomK(i+2))

    test "Field axioms":
      for i in 0 ..< Iters:
        let a = rng.randomK(i)
        let b = rng.randomK(i+1)
        let c = rng.randomK(i+2)
        check:
          bool(a * b == b * a)
          bool((a * b) * c == a * (b * c))
          bool(a * (b + c) == a * b + a * c)
          bool(a + a == GF2_64.getZero())
          bool(a - b == a + b)
          bool(a * GF2_64.getOne() == a)

    test "Inversion":
      var z = GF2_64.getZero()
      z.inv()
      check: bool z.isZero()
      for c in Corners[1..^1]:
        let a = GF2_64.fromRaw(c)
        var ai: GF2_64
        ai.inv(a)
        check: bool (a * ai).isOne()
      for i in 0 ..< Iters:
        let a = rng.randomK(i)
        var ai: GF2_64
        ai.inv(a)
        if bool a.isZero():
          check: bool ai.isZero()
        else:
          check: bool (a * ai).isOne()

    test "Frobenius: 64 squarings are the identity":
      for i in 0 ..< 200:
        let a = rng.randomK(i)
        var r: GF2_64
        r.square_repeated(a, 64)
        check: bool(r == a)

    test "Multiplication and division by the generator x":
      let x = GF2_64.generator()
      for i in 0 ..< Iters:
        let a = rng.randomK(i)
        var r, back: GF2_64
        r.mulByX(a)
        check: bool(r == a * x)
        back.divByX(r)
        check: bool(back == a)

    test "Constantine's generic exponentiation: x^k is bit k for k < 64, xᵏ order 2⁶⁴-1":
      for k in 0'u64 ..< 64:
        var g = GF2_64.generator()
        g.pow_vartime(k)
        check: g.raw == 1'u64 shl k

      for i in 0 ..< 100:
        let a = rng.randomK(i)
        # Small exponents against a running product
        var want = GF2_64.getOne()
        for e in 0'u64 ..< 20:
          var p = a
          p.pow_vartime(e)
          check: bool(p == want)
          want *= a
        # Fermat: a^(2⁶⁴-1) = 1 for a ≠ 0
        var p = a
        p.pow_vartime(high(uint64))
        if not bool(a.isZero()):
          check: bool p.isOne()

    test "Constantine's generic batch inversion, including zeros":
      const N = 37
      var src, dst, dstVartime: array[N, GF2_64]
      for i in 0 ..< N:
        src[i] = if i mod 7 == 3: GF2_64.getZero() else: rng.randomK(i)
      dst.batchInv(src)
      dstVartime.batchInv_vartime(src)
      for i in 0 ..< N:
        var want: GF2_64
        want.inv(src[i])
        check:
          bool(dst[i] == want)
          bool(dstVartime[i] == want)

    test "Unreduced accumulation equals the sum of reduced products":
      for _ in 0 ..< 100:
        var acc, t: GF2_64Dbl
        var want: GF2_64
        acc.setZero()
        want.setZero()
        for j in 0 ..< 16:
          let a = rng.randomK(j)
          let b = rng.randomK(j+1)
          t.prod2x(a, b)
          acc += t
          want += a * b
        var r: GF2_64
        r.redc2x(acc)
        check: bool(r == want)

    test "Constant-time selection and predicates":
      for i in 0 ..< 100:
        let a = rng.randomK(i)
        let b = rng.randomK(i+1)
        var r = a
        r.ccopy(b, CtFalse)
        check: bool(r == a)
        r.ccopy(b, CtTrue)
        check: bool(r == b)
        r = a
        r.csetZero(CtFalse)
        check: bool(r == a)
        r.csetZero(CtTrue)
        check: bool r.isZero()
        r = a
        r.csetOne(CtTrue)
        check: bool r.isOne()
        r = a
        r.cadd(b, CtFalse)
        check: bool(r == a)
        r.cadd(b, CtTrue)
        check: bool(r == a + b)
      check:
        bool GF2_64.getOne().isMinusOne()
        not bool GF2_64.generator().isOne()

    test "Characteristic 2 has no division by 2":
      var a: GF2_64
      check: not compiles(a.div2())

    test "Serialization: little-endian is leanVM's wire format, round trips":
      for i in 0 ..< 100:
        let a = rng.randomK(i)
        var le, be: array[8, byte]
        check:
          le.marshal(a, littleEndian)
          be.marshal(a, bigEndian)
        for j in 0 ..< 8:
          check:
            le[j] == byte((a.raw shr (8*j)) and 0xFF)
            be[j] == le[7-j]
        var b: GF2_64
        check:
          b.unmarshal(le, littleEndian)
          bool(a == b)
          bool(GF2_64.fromHex(a.toHex()) == a)
      check: GF2_64.fromRaw(0x1B).toHex() == "0x000000000000001b"
      var short: array[7, byte]
      check: not short.marshal(GF2_64.getOne(), littleEndian)

main()
