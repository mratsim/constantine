# 𝔽₂⁶⁴ = 𝔽₂[x]/(x⁶⁴ + x⁴ + x³ + x + 1), leanVM's base field K

const Iters = 2000

var rng: RngState
let seed = uint32(getTime().toUnix() and (1'i64 shl 32 - 1)) # unixTime mod 2^32
rng.seed(seed)
echo "\n------------------------------------------------------\n"
echo "t_gf2_64 xoshiro512** seed: ", seed
